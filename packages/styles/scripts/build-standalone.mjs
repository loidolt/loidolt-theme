/*
 * Builds the self-contained stylesheets in `dist/` for pages that cannot resolve `@import`s or
 * relative font URLs: a generated HTML report, an email-like single file, a page with no build
 * step. Each output inlines every `@import` (wrapping layered ones in `@layer <name> { … }`, which
 * is what `@import … layer(<name>)` means) so the file can be pasted into one `<style>` element.
 *
 *   standalone.css       index.css + dark-auto: tokens, base, every component group, utilities,
 *                        accessibility. No @font-face, so it never points at a missing file; the
 *                        font stacks fall back to system fonts.
 *   standalone-core.css  The same built from core.css: no media, charts, maps, prose or docs.
 *   fonts-embedded.css   The two @font-face rules with the WOFF2 files as base64 data URIs.
 *
 * No dependencies: the inputs are this package's own CSS, whose `@import` syntax is fixed.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const dist = path.join(root, 'dist');
const require = createRequire(path.join(root, 'package.json'));
const { version } = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');
const importPattern = /@import\s+(?:url\()?['"]([^'"]+)['"]\)?\s*([^;]*);/g;

/** `./x.css` relative to the importing file, anything else through package exports. */
function resolve(target, from) {
  return target.startsWith('.')
    ? path.resolve(path.dirname(from), target)
    : require.resolve(target);
}

/** Inline every import of `file`, recursively. `skip` lists files left out entirely. */
function bundle(file, skip, seen = new Set()) {
  if (seen.has(file)) throw new Error(`Circular @import: ${file}`);
  const next = new Set(seen).add(file);
  return stripComments(readFileSync(file, 'utf8')).replace(importPattern, (_, target, rest) => {
    const resolved = resolve(target, file);
    if (skip.has(resolved)) return '';
    const body = bundle(resolved, skip, next).trim();
    const layer = rest.trim().match(/^layer\(([\w.-]+)\)$/);
    if (rest.trim() && !layer) throw new Error(`Unsupported @import condition: ${rest}`);
    return layer ? `@layer ${layer[1]} {\n${body}\n}` : body;
  });
}

const tidy = (css) =>
  css
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim() + '\n';

const header = (what) =>
  `/* @loidolt/theme-styles ${version} — ${what}\n   Generated by scripts/build-standalone.mjs. Do not edit directly. MIT licensed. */\n`;

const noFonts = new Set([path.join(src, 'fonts.css')]);
const darkAuto = bundle(path.join(src, 'dark-auto.css'), noFonts).trim();
/*
 * dark-auto stays unlayered after everything else, exactly as `@import '…/dark-auto'` after the
 * main stylesheet leaves it. Inside a layer its `color-scheme: dark` would lose to the
 * `color-scheme: light` in the base layer, and native controls and scrollbars would stay light.
 * A preset appended after this file still overrides it the same way it does in a bundled app.
 */
const withDarkAuto = (entry) => `${bundle(path.join(src, entry), noFonts).trim()}\n\n${darkAuto}`;

const faces = [
  { family: 'Jost', file: 'Jost-Medium.woff2', weight: 500 },
  { family: 'Archivo', file: 'Archivo-Regular.woff2', weight: 400 },
];
const fontsEmbedded = faces
  .map(({ family, file, weight }) => {
    const data = readFileSync(path.join(src, 'fonts', file)).toString('base64');
    return `@font-face {
  font-family: '${family}';
  src: url('data:font/woff2;base64,${data}') format('woff2');
  font-weight: ${weight};
  font-style: normal;
  font-display: swap;
}`;
  })
  .join('\n\n');

const outputs = {
  'standalone.css':
    header('the whole stylesheet with dark-auto, no @import, no font files') +
    withDarkAuto('index.css'),
  'standalone-core.css':
    header('core with dark-auto, no @import, no font files') + withDarkAuto('core.css'),
  'fonts-embedded.css':
    header(
      'Jost and Archivo as data URIs. Fonts: SIL Open Font License 1.1, see src/fonts/*-LICENSE.txt'
    ) + fontsEmbedded,
};

mkdirSync(dist, { recursive: true });
for (const [name, css] of Object.entries(outputs)) {
  const out = tidy(css);
  if (/@import\b/.test(stripComments(out))) throw new Error(`${name} still contains an @import`);
  writeFileSync(path.join(dist, name), out);
  console.log(`theme-styles: dist/${name} ${(Buffer.byteLength(out) / 1024).toFixed(1)} kB`);
}
